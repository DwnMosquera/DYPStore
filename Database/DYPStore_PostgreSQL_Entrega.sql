-- Motor: PostgreSQL 14 / 15 / 16 (Compatible con Supabase y Neon Database)
-- Mapeo ORM: Entity Framework Core 8.0 (Npgsql.EntityFrameworkCore.PostgreSQL)
-- Archivo Destino: Database/DYPStore_PostgreSQL_Entrega.sql
--
-- ============================================================================
-- NOTA TÉCNICA Y AUDITORÍA DE DISCREPANCIAS CON RESPECTO AL SCRIPT ORIGINAL:
-- ============================================================================
-- 1. MOTOR DE BASE DE DATOS:
--    El archivo legacy original "Database/DYPStore_Script.sql" fue redactado
--    utilizando la sintaxis privativa de Microsoft SQL Server (T-SQL: USE master,
--    DB_ID, datetime2, nvarchar(max), IDENTITY, GETUTCDATE()).
--    Este nuevo script es 100% nativo para PostgreSQL (timestamp with time zone,
--    GENERATED BY DEFAULT AS IDENTITY, text, character varying, numeric(18,2)).
--
-- 2. TABLAS FALTANTES EN EL SCRIPT ANTERIOR:
--    El script anterior omitía por completo tres entidades críticas del sistema:
--    - "FaceEnrollments": Requerida para el inicio de sesión biométrico Face ID.
--    - "ChatLogs": Requerida para la auditoría y monitoreo del Chatbot con IA.
--    - "DataProtectionKeys": Requerida para persistencia de claves criptográficas.
--
-- 3. RESTRICCIONES CHECK DE NEGOCIO:
--    Este script incorpora formalmente las restricciones CHECK configuradas
--    en ApplicationDbContext.cs para prevenir valores negativos en inventario,
--    precios y cantidades.
--
-- 4. POLÍTICAS NO DESTRUCTIVAS:
--    Este script NO contiene comandos DROP DATABASE, DROP TABLE ni sentencias
--    destructivas. Utiliza "CREATE TABLE IF NOT EXISTS" e inserciones con
--    "ON CONFLICT DO NOTHING" garantizando idempotencia y preservación de datos.
-- ============================================================================

-- 1. TABLAS DEL SUBSISTEMA DE AUTENTICACIÓN (ASP.NET CORE IDENTITY)

-- Tabla: AspNetRoles
CREATE TABLE IF NOT EXISTS "AspNetRoles" (
    "Id" text NOT NULL,
    "Name" character varying(256) NULL,
    "NormalizedName" character varying(256) NULL,
    "ConcurrencyStamp" text NULL,
    CONSTRAINT "PK_AspNetRoles" PRIMARY KEY ("Id")
);

-- Tabla: AspNetUsers
CREATE TABLE IF NOT EXISTS "AspNetUsers" (
    "Id" text NOT NULL,
    "FullName" text NOT NULL DEFAULT '',
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UserName" character varying(256) NULL,
    "NormalizedUserName" character varying(256) NULL,
    "Email" character varying(256) NULL,
    "NormalizedEmail" character varying(256) NULL,
    "EmailConfirmed" boolean NOT NULL DEFAULT FALSE,
    "PasswordHash" text NULL,
    "SecurityStamp" text NULL,
    "ConcurrencyStamp" text NULL,
    "PhoneNumber" text NULL,
    "PhoneNumberConfirmed" boolean NOT NULL DEFAULT FALSE,
    "TwoFactorEnabled" boolean NOT NULL DEFAULT FALSE,
    "LockoutEnd" timestamp with time zone NULL,
    "LockoutEnabled" boolean NOT NULL DEFAULT TRUE,
    "AccessFailedCount" integer NOT NULL DEFAULT 0,
    CONSTRAINT "PK_AspNetUsers" PRIMARY KEY ("Id")
);

-- Tabla: AspNetRoleClaims
CREATE TABLE IF NOT EXISTS "AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "RoleId" text NOT NULL,
    "ClaimType" text NULL,
    "ClaimValue" text NULL,
    CONSTRAINT "PK_AspNetRoleClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetRoleClaims_AspNetRoles_RoleId" FOREIGN KEY ("RoleId")
        REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE
);

-- Tabla: AspNetUserClaims
CREATE TABLE IF NOT EXISTS "AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" text NOT NULL,
    "ClaimType" text NULL,
    "ClaimValue" text NULL,
    CONSTRAINT "PK_AspNetUserClaims" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_AspNetUserClaims_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- Tabla: AspNetUserLogins
CREATE TABLE IF NOT EXISTS "AspNetUserLogins" (
    "LoginProvider" text NOT NULL,
    "ProviderKey" text NOT NULL,
    "ProviderDisplayName" text NULL,
    "UserId" text NOT NULL,
    CONSTRAINT "PK_AspNetUserLogins" PRIMARY KEY ("LoginProvider", "ProviderKey"),
    CONSTRAINT "FK_AspNetUserLogins_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- Tabla: AspNetUserRoles
CREATE TABLE IF NOT EXISTS "AspNetUserRoles" (
    "UserId" text NOT NULL,
    "RoleId" text NOT NULL,
    CONSTRAINT "PK_AspNetUserRoles" PRIMARY KEY ("UserId", "RoleId"),
    CONSTRAINT "FK_AspNetUserRoles_AspNetRoles_RoleId" FOREIGN KEY ("RoleId")
        REFERENCES "AspNetRoles" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_AspNetUserRoles_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- Tabla: AspNetUserTokens
CREATE TABLE IF NOT EXISTS "AspNetUserTokens" (
    "UserId" text NOT NULL,
    "LoginProvider" text NOT NULL,
    "Name" text NOT NULL,
    "Value" text NULL,
    CONSTRAINT "PK_AspNetUserTokens" PRIMARY KEY ("UserId", "LoginProvider", "Name"),
    CONSTRAINT "FK_AspNetUserTokens_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);


-- 2. TABLAS DEL DOMINIO DE COMERCIO ELECTRÓNICO (DYPSTORE)

-- Tabla: Products (Catálogo deportivo)
CREATE TABLE IF NOT EXISTS "Products" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "Name" character varying(200) NOT NULL,
    "Description" text NOT NULL,
    "Brand" character varying(100) NOT NULL,
    "Price" numeric(18,2) NOT NULL,
    "Stock" integer NOT NULL DEFAULT 0,
    "Category" text NOT NULL,
    "ImageUrl" text NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_Products" PRIMARY KEY ("Id"),
    CONSTRAINT "CK_Product_Stock_Positive" CHECK ("Stock" >= 0),
    CONSTRAINT "CK_Product_Price_Positive" CHECK ("Price" >= 0)
);

-- Tabla: Orders (Cabecera de pedidos)
CREATE TABLE IF NOT EXISTS "Orders" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" text NOT NULL,
    "Total" numeric(18,2) NOT NULL DEFAULT 0.00,
    "Status" text NOT NULL DEFAULT 'pending',
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_Orders" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_Orders_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "CK_Order_Total_Positive" CHECK ("Total" >= 0)
);

-- Tabla: CartItems (Carrito de compras)
CREATE TABLE IF NOT EXISTS "CartItems" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" text NOT NULL,
    "ProductId" integer NOT NULL,
    "Quantity" integer NOT NULL DEFAULT 1,
    "AddedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_CartItems" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_CartItems_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_CartItems_Products_ProductId" FOREIGN KEY ("ProductId")
        REFERENCES "Products" ("Id") ON DELETE CASCADE,
    CONSTRAINT "CK_CartItem_Quantity_Positive" CHECK ("Quantity" > 0)
);

-- Tabla: OrderItems (Líneas de detalle de pedidos)
CREATE TABLE IF NOT EXISTS "OrderItems" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "OrderId" integer NOT NULL,
    "ProductId" integer NOT NULL,
    "ProductName" text NOT NULL,
    "UnitPrice" numeric(18,2) NOT NULL,
    "Quantity" integer NOT NULL,
    CONSTRAINT "PK_OrderItems" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_OrderItems_Orders_OrderId" FOREIGN KEY ("OrderId")
        REFERENCES "Orders" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_OrderItems_Products_ProductId" FOREIGN KEY ("ProductId")
        REFERENCES "Products" ("Id") ON DELETE CASCADE,
    CONSTRAINT "CK_OrderItem_Quantity_Positive" CHECK ("Quantity" > 0),
    CONSTRAINT "CK_OrderItem_UnitPrice_Positive" CHECK ("UnitPrice" >= 0)
);


-- 3. TABLAS DE INTELIGENCIA ARTIFICIAL, BIOMETRÍA Y SEGURIDAD

-- Tabla: FaceEnrollments (Biometría facial 128D Face ID)
CREATE TABLE IF NOT EXISTS "FaceEnrollments" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" text NOT NULL,
    "DescriptorJson" text NOT NULL,
    "FrameCount" integer NOT NULL DEFAULT 1,
    "UserAgent" character varying(300) NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_FaceEnrollments" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_FaceEnrollments_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE CASCADE
);

-- Tabla: ChatLogs (Auditoría del Asistente Virtual / Chatbot)
CREATE TABLE IF NOT EXISTS "ChatLogs" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "UserId" text NULL,
    "UserEmail" character varying(256) NOT NULL DEFAULT '',
    "UserRole" character varying(20) NOT NULL DEFAULT 'User',
    "Message" character varying(500) NOT NULL,
    "Intent" character varying(60) NOT NULL DEFAULT '',
    "IsSuccess" boolean NOT NULL DEFAULT TRUE,
    "IsWriteAction" boolean NOT NULL DEFAULT FALSE,
    "IpAddress" character varying(60) NULL,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "PK_ChatLogs" PRIMARY KEY ("Id"),
    CONSTRAINT "FK_ChatLogs_AspNetUsers_UserId" FOREIGN KEY ("UserId")
        REFERENCES "AspNetUsers" ("Id") ON DELETE SET NULL
);

-- Tabla: DataProtectionKeys (Persistencia de claves criptográficas de sesión)
CREATE TABLE IF NOT EXISTS "DataProtectionKeys" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY,
    "FriendlyName" text NULL,
    "Xml" text NOT NULL,
    CONSTRAINT "PK_DataProtectionKeys" PRIMARY KEY ("Id")
);


-- 4. ÍNDICES DE RENDIMIENTO Y UNICIDAD (B-TREE POSTGRESQL)

-- Índices en AspNetUsers y AspNetRoles
CREATE UNIQUE INDEX IF NOT EXISTS "UserNameIndex" ON "AspNetUsers" ("NormalizedUserName");
CREATE INDEX IF NOT EXISTS "EmailIndex" ON "AspNetUsers" ("NormalizedEmail");
CREATE UNIQUE INDEX IF NOT EXISTS "RoleNameIndex" ON "AspNetRoles" ("NormalizedName");

-- Índices en tablas asociativas de Identity
CREATE INDEX IF NOT EXISTS "IX_AspNetRoleClaims_RoleId" ON "AspNetRoleClaims" ("RoleId");
CREATE INDEX IF NOT EXISTS "IX_AspNetUserClaims_UserId" ON "AspNetUserClaims" ("UserId");
CREATE INDEX IF NOT EXISTS "IX_AspNetUserLogins_UserId" ON "AspNetUserLogins" ("UserId");
CREATE INDEX IF NOT EXISTS "IX_AspNetUserRoles_RoleId" ON "AspNetUserRoles" ("RoleId");

-- Índices en Carrito y Pedidos
CREATE INDEX IF NOT EXISTS "IX_CartItems_UserId" ON "CartItems" ("UserId");
CREATE INDEX IF NOT EXISTS "IX_CartItems_ProductId" ON "CartItems" ("ProductId");
CREATE INDEX IF NOT EXISTS "IX_Orders_UserId" ON "Orders" ("UserId");
CREATE INDEX IF NOT EXISTS "IX_OrderItems_OrderId" ON "OrderItems" ("OrderId");
CREATE INDEX IF NOT EXISTS "IX_OrderItems_ProductId" ON "OrderItems" ("ProductId");

-- Índice Único de Biometría (Garantiza a lo sumo 1 registro por usuario)
CREATE UNIQUE INDEX IF NOT EXISTS "IX_FaceEnrollments_UserId" ON "FaceEnrollments" ("UserId");

-- Índices en Auditoría de Chat
CREATE INDEX IF NOT EXISTS "IX_ChatLogs_UserId" ON "ChatLogs" ("UserId");
CREATE INDEX IF NOT EXISTS "IX_ChatLogs_CreatedAt" ON "ChatLogs" ("CreatedAt");


